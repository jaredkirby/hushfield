import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { TapeLoop } from '../dist/tape-physics.mjs';

// Run offline once, then ship the paused particle positions. Page loads
// never have to run the warm-up simulation themselves.
const seconds = 45, speed = 1, stiffness = .8;
const tape = new TapeLoop();
for (let i = 0; i < seconds * 120; i++) tape.step(1 / 120, speed, stiffness);
const health = tape.health();
let minimumGap = Infinity;
for (const [i,j] of tape.pairs(13)) minimumGap = Math.min(minimumGap, tape.closest(i,j).d);
assert(health.finite && health.lengthError < .02 && minimumGap > 11, 'Snapshot must be finite and separated');
const snapshot = {
  version: 1, capturedAfterSeconds: seconds, speed, stiffness,
  length: tape.length, transportLength: tape.transportLength, travel: tape.travel,
  x: Array.from(tape.x), y: Array.from(tape.y)
};
await writeFile(new URL('../dist/tape-initial-state.mjs', import.meta.url),
  '// Generated by node ops/capture-tape-start.mjs. A paused, pre-run tape loop.\n'
  + 'export const TAPE_INITIAL_STATE = ' + JSON.stringify(snapshot, null, 2) + ';\n');
console.log({ capturedAfterSeconds: seconds, minimumGap, ...health });
