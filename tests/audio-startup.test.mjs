import assert from 'node:assert/strict';
import { requestPlaybackSession, resumeFromTap, primeAudioOutput, verifyAudioClock, retireAudioContext } from '../dist/audio-startup.mjs';
const calls=[];
const session={set type(value){calls.push('session:'+value);this.value=value;},get type(){return this.value;}};
const context={state:'suspended',resume(){calls.push('resume');this.state='running';return Promise.resolve();}};
const activation=resumeFromTap(context,{audioSession:session});
calls.push('begin asynchronous worklet fetch');
assert.deepEqual(calls,['session:playback','resume','begin asynchronous worklet fetch'],'Audio must resume before the worklet network await');
await activation;
assert.equal(requestPlaybackSession({}),false,'Missing AudioSession does not block playback');
assert.equal(requestPlaybackSession({get audioSession(){throw Error('unsupported');}}),false);
let fallbackResumed=false;await resumeFromTap({state:'running',resume(){fallbackResumed=true;return Promise.resolve();}},{});assert(fallbackResumed);
await assert.rejects(resumeFromTap({state:'suspended',resume:()=>Promise.resolve()},{}),/suspended/,'Do not report success for a still-suspended context');
await assert.rejects(resumeFromTap({state:'suspended',resume:()=>new Promise(()=>{})},{},10),/not enabled audio/,'Blocked activation must time out with a retry path');
await assert.rejects(resumeFromTap({state:'closed'},{}),/Reload/);
await assert.rejects(resumeFromTap({state:'suspended',resume(){throw Error('denied');}},{}),/denied/);
const order=[];
const source={connect(){order.push('connect output');},start(){order.push('start source');},disconnect(){order.push('disconnect source');}};
const primed={state:'suspended',sampleRate:48000,destination:{},createBufferSource:()=>source,createBuffer:(...args)=>{assert.deepEqual(args,[1,32,48000]);return {};},resume(){order.push('resume');this.state='running';return Promise.resolve();}};
const tapped=resumeFromTap(primed,{});order.push('fetch worklet');await tapped;
assert.deepEqual(order,['resume','connect output','start source','fetch worklet'],'An actual source starts inside the gesture before asynchronous engine loading');
source.onended();assert.equal(order.at(-1),'disconnect source');
assert.equal(primeAudioOutput({}),false);
assert.equal(primeAudioOutput({createBufferSource(){throw Error('unavailable');},createBuffer(){},destination:{}}),false);
let sessionWrites=0;
assert.equal(requestPlaybackSession({audioSession:{get type(){return 'playback';},set type(_){sessionWrites++;}}}),true);
assert.equal(sessionWrites,0,'Do not interrupt an already-selected playback session');
await assert.rejects(verifyAudioClock({state:'running',currentTime:1},1),/clock stopped/,'A running state alone must not hide a stalled device clock');
let clock=0;await verifyAudioClock({state:'running',get currentTime(){return clock+=.1;}},1);
await assert.rejects(verifyAudioClock({state:'interrupted',currentTime:1},1),/paused/);
const retiring={onstatechange(){},close(){order.push('close old context');return Promise.resolve();}};
retireAudioContext(retiring);order.push('new gesture context');
assert.equal(retiring.onstatechange,null);
assert.deepEqual(order.slice(-2),['close old context','new gesture context'],'Retirement must not await and lose the fresh tap activation');
console.log('PASS: playback session, direct tap resume/source priming, clock-stall detection, context retirement, feature fallback and bounded activation.');
